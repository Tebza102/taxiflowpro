#!/usr/bin/env node
// Isolated LOCAL TaxiFlow Supabase (Docker Compose, loopback-only ports).
//   node scripts/localdb/setup.mjs prepare   copy compose files; generate local .env + kong.yml once
//   node scripts/localdb/setup.mjs start     up (existing volume), check bindings + Windows listeners
//   node scripts/localdb/setup.mjs reset     fresh volume, migrations + synthetic seed
//   node scripts/localdb/setup.mjs schema    fresh volume, migrations only (used by the drill)
//   node scripts/localdb/setup.mjs stop      down, keeping the volume
// Any published service reachable beyond 127.0.0.1 stops the stack immediately.
import { copyFileSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  COMPOSE_DIR,
  ENV_FILE,
  REPO_ROOT,
  WORKDIR,
  assertLocalDatabase,
  assertLoopbackOnlyOrStop,
  compose,
  generateLocalSecrets,
  psql,
  readLocalEnv,
  removeComposeVolume,
} from "./lib/exec.mjs";
import { CLI_DISABLED_CONFIG, CLI_DISABLED_SENTINEL } from "./lib/localTarget.mjs";
import { buildSeedSql } from "./seed-data.mjs";

const SOURCE = path.join(REPO_ROOT, "scripts", "localdb");
export const MIGRATIONS_DIR = path.join(SOURCE, "migrations");

export const prepare = () => {
  // Disable the Supabase CLI in the workdir before anything else (see localTarget.mjs).
  const cliConfig = path.join(WORKDIR, "supabase", "config.toml");
  mkdirSync(path.dirname(cliConfig), { recursive: true });
  if (existsSync(cliConfig) && !readFileSync(cliConfig, "utf8").includes(CLI_DISABLED_SENTINEL)) {
    throw new Error(`${cliConfig} is an active Supabase CLI config; move it aside (it is preserved in backups) before using the Compose stack.`);
  }
  writeFileSync(cliConfig, CLI_DISABLED_CONFIG);
  mkdirSync(path.join(COMPOSE_DIR, "db-init"), { recursive: true });
  copyFileSync(path.join(SOURCE, "compose", "docker-compose.yml"), path.join(COMPOSE_DIR, "docker-compose.yml"));
  for (const file of ["roles.sql", "jwt.sql"]) {
    copyFileSync(path.join(SOURCE, "compose", "db-init", file), path.join(COMPOSE_DIR, "db-init", file));
  }
  if (!existsSync(ENV_FILE)) {
    const secrets = generateLocalSecrets();
    writeFileSync(
      ENV_FILE,
      `# LOCAL ONLY - generated by scripts/localdb/setup.mjs; never copy to the repo or a hosted project.\n${Object.entries(secrets)
        .map(([key, value]) => `${key}=${value}`)
        .join("\n")}\n`,
      { mode: 0o600 },
    );
  }
  const env = readLocalEnv();
  const kong = readFileSync(path.join(SOURCE, "compose", "kong.template.yml"), "utf8")
    .replaceAll("__ANON_KEY__", env.ANON_KEY)
    .replaceAll("__SERVICE_ROLE_KEY__", env.SERVICE_ROLE_KEY);
  if (/__(ANON|SERVICE_ROLE)_KEY__/.test(kong)) throw new Error("kong.yml still has key placeholders");
  writeFileSync(path.join(COMPOSE_DIR, "kong.yml"), kong, { mode: 0o600 });
  console.log(`[localdb] compose files ready in ${COMPOSE_DIR}`);
};

const waitFor = (label, check, attempts = 60) => {
  for (let i = 0; i < attempts; i += 1) {
    if (check()) return;
    Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 2000);
  }
  throw new Error(`Timed out waiting for ${label}.`);
};

export const start = () => {
  prepare();
  compose(["up", "-d", "--wait", "--wait-timeout", "300"]);
  const { bindings, listeners } = assertLoopbackOnlyOrStop();
  console.log(`[localdb] up; bindings ${bindings.join(", ")}; Windows listeners ${listeners.map((l) => `${l.address}:${l.port}`).join(", ")}`);
};

// Fresh volume -> wait for GoTrue to create auth.users -> apply migrations in
// filename order -> optional synthetic seed. Only the local Compose volume is
// ever removed (ownership label checked).
export const rebuild = ({ seed }) => {
  prepare();
  compose(["down"]);
  removeComposeVolume();
  start();
  waitFor("auth.users (GoTrue migrations)", () => psql("select to_regclass('auth.users') is not null;", { allowFailure: true }).stdout.trim() === "t");
  const files = readdirSync(MIGRATIONS_DIR).filter((name) => name.endsWith(".sql")).sort();
  for (const file of files) {
    psql(readFileSync(path.join(MIGRATIONS_DIR, file), "utf8").replace(/^/, "begin;\n") + "\ncommit;\n");
    console.log(`[localdb] applied ${file}`);
  }
  assertLocalDatabase();
  if (seed) {
    psql(buildSeedSql());
    console.log("[localdb] synthetic seed loaded");
  }
};

const mode = process.argv[2];
const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (mode === "prepare") prepare();
  else if (mode === "start") start();
  else if (mode === "reset") rebuild({ seed: true });
  else if (mode === "schema") rebuild({ seed: false });
  else if (mode === "stop") compose(["down"]);
  else {
    console.error("Usage: node scripts/localdb/setup.mjs prepare|start|reset|schema|stop");
    process.exit(2);
  }
  console.log(`[localdb] ${mode} done (${WORKDIR})`);
}
