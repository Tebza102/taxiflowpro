#!/usr/bin/env node
// Builds scripts/preview-test/schema.sql: SCHEMA ONLY for the EMPTY isolated
// Preview test project (taxiflow-preview-test, sxoonhovoqgcpflhqirb), to be run
// by Tebogo in that project's SQL editor. Generated from the repository's
// release files so nothing is retyped by hand:
//   * the app table as production has it, but with no browser policies;
//   * release files 01-06 (scripts/hosted/apply-release.mjs RELEASE_FILES), with
//     exactly two segments of 01 removed, because a fresh project has no legacy
//     workspace: the legacy-workspace mapping (one business row, one update,
//     the membership backfill from appUsers) and the closing assertion that
//     this legacy workspace has an active Owner. Every security assertion stays.
// No accounts, no credentials, no data. One transaction; refuses to run on a
// project that already has users or TaxiFlow tables.
//   node scripts/preview-test/build-schema.mjs
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

import { RELEASE_FILES } from "../hosted/apply-release.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..", "..");
const OUT = path.join(ROOT, "scripts", "preview-test", "schema.sql");
const read = (file) => readFileSync(path.join(ROOT, file), "utf8").replace(/\r\n/g, "\n");

const remove = (text, segment, label) => {
  const count = text.split(segment).length - 1;
  if (count !== 1) throw new Error(`Expected exactly one "${label}" segment in release file 01, found ${count}.`);
  return text.replace(segment, `-- [Preview test schema] removed: ${label} (no legacy workspace in a fresh project).\n`);
};

let foundation = read(RELEASE_FILES[0].file);
foundation = remove(
  foundation,
  `insert into public.businesses (id, slug, name)
values ('10000000-0000-4000-8000-00000000000a', 'taxiflow-legacy', 'TaxiFlow Pro')
on conflict (id) do nothing;

update public.workspace_snapshots
set business_id = '10000000-0000-4000-8000-00000000000a'
where workspace_key = 'taxiflow-live' and business_id is null;
`,
  "legacy business row and workspace mapping",
);
foundation = remove(
  foundation,
  `-- Memberships only for exact, active, allowed-role appUsers matches. Unmatched
-- accounts get no access (fail closed). Viewer is never a membership.
insert into public.business_memberships (business_id, user_id, role, driver_staff_id, active)
select s.business_id, u.id, a ->> 'role', nullif(trim(a ->> 'staffId'), ''), true
from public.workspace_snapshots s
cross join lateral jsonb_array_elements(coalesce(s.snapshot -> 'appUsers', '[]'::jsonb)) a
join auth.users u on lower(u.email) = lower(trim(a ->> 'email'))
where s.workspace_key = 'taxiflow-live'
  and coalesce((a ->> 'active')::boolean, true)
  and a ->> 'role' in ('Owner', 'Admin', 'Manager', 'Driver')
  and (a ->> 'role' <> 'Driver' or nullif(trim(a ->> 'staffId'), '') is not null)
on conflict (business_id, user_id) do nothing;
`,
  "legacy membership backfill from appUsers",
);
foundation = remove(
  foundation,
  `
  if not exists (
    select 1 from public.business_memberships m
    where m.business_id = '10000000-0000-4000-8000-00000000000a' and m.role = 'Owner' and m.active
  ) then
    raise exception 'The existing workspace would have no active Owner; stop and add the operator Owner step first.';
  end if;
`,
  "legacy-workspace Owner assertion",
);

const header = `-- TaxiFlow Pro: SCHEMA ONLY for the isolated Preview TEST project
--   taxiflow-preview-test (ref sxoonhovoqgcpflhqirb). NEVER production
--   (vfxftviwteypasredjgm).
-- GENERATED by scripts/preview-test/build-schema.mjs from the release files;
-- do not edit by hand. Creates no accounts, holds no credentials and no data.
-- Runs as one transaction: any failed check rolls everything back.

begin;

-- Refuse anything but an EMPTY project (production has users and these tables).
do $$ begin
  if exists (select 1 from auth.users) then
    raise exception 'Refusing: this project already has sign-in accounts. Run only on the empty taxiflow-preview-test project.';
  end if;
  if to_regclass('public.workspace_snapshots') is not null or to_regclass('public.businesses') is not null then
    raise exception 'Refusing: TaxiFlow tables already exist in this project.';
  end if;
end $$;

-- The app table as production has it, without production's legacy browser
-- policies (release file 01 would remove them anyway).
create table public.workspace_snapshots (
  workspace_key text primary key,
  snapshot jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id)
);
alter table public.workspace_snapshots enable row level security;
revoke all on table public.workspace_snapshots from anon, authenticated, public;
`;

const footer = `
commit;
`;

const body = [
  `-- ===== ${RELEASE_FILES[0].label} (two legacy-only segments removed, see above) =====\n${foundation}`,
  ...RELEASE_FILES.slice(1).map((entry) => `-- ===== ${entry.label} (${entry.file}, unchanged) =====\n${read(entry.file)}`),
].join("\n\n");

const sql = `${header}\n${body}\n${footer}`;
for (const forbidden of [/insert\s+into\s+auth\./i, /sb_secret_|service_role_key|eyJhbGciOi/i, /\$2[aby]\$\d\d\$/, /encrypted_password/i, /@example\.com|@gmail\.com|apprigate\.com/i]) {
  if (forbidden.test(sql)) throw new Error(`The schema file contains forbidden content: ${forbidden}`);
}
writeFileSync(OUT, sql);
console.log(`${path.relative(ROOT, OUT)} written (${sql.split("\n").length} lines)`);
